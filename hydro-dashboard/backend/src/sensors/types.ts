// รูปแบบมาตรฐานของ "โมดูลเซนเซอร์" 1 ตัว = 1 ไฟล์ในโฟลเดอร์นี้
export interface SensorModule {
  /** คอลัมน์ในตาราง sensor_logs */
  col: string
  /** ชื่อฟิลด์ใน JSON ที่ ESP32 ส่งมา (ชื่อแรกคือชื่อมาตรฐาน ที่เหลือเป็นชื่อที่ยอมรับเพิ่ม) */
  aliases: string[]
  /** ช่วงค่าที่สมเหตุสมผล นอกช่วง = ทิ้งค่านั้น (กันค่าเพี้ยนจากเซนเซอร์หลุด/สายหลวม) */
  min: number
  max: number
  /** ชื่อและหน่วย ไว้ใช้ใน log/เอกสาร */
  label: string
  unit: string
  /** (ไม่บังคับ) ปรับแต่งค่าหลังผ่านการตรวจช่วง เช่น ปัดทศนิยม แปลงหน่วย คืน null = ทิ้งค่า */
  transform?: (value: number) => number | null
}
